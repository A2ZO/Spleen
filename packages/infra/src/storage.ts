import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import { DeleteObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";

import { isProduction, s3Configured } from "./config";
import { devUploadsDir } from "./paths";

/** File storage behind the S3 API (Cloudflare R2 in production). */
export interface Storage {
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  delete(key: string): Promise<void>;
  /** URL the browser loads the object from. */
  publicUrl(key: string): string;
  /** Key of an object from its public URL, or null if the URL is not ours. */
  keyFromUrl(url: string): string | null;
}

/** Keys are generated by us: lowercase segments, no dot-dot, no leading slash. */
const KEY_PATTERN = /^[a-z0-9_-]+(?:\/[a-z0-9_-]+)*\.[a-z0-9]+$/;

export function assertValidKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error("Invalid storage key.");
}

function prefixStorage(base: string, ops: Pick<Storage, "put" | "delete">): Storage {
  const prefix = base.endsWith("/") ? base : `${base}/`;
  return {
    put: async (key, body, contentType) => {
      assertValidKey(key);
      return ops.put(key, body, contentType);
    },
    delete: async (key) => {
      assertValidKey(key);
      return ops.delete(key);
    },
    publicUrl: (key) => `${prefix}${key}`,
    keyFromUrl: (url) => {
      if (!url.startsWith(prefix)) return null;
      const key = url.slice(prefix.length);
      return KEY_PATTERN.test(key) ? key : null;
    },
  };
}

export function createS3Storage(options: {
  endpoint: string;
  region: string;
  bucket: string;
  accessKeyId: string;
  secretAccessKey: string;
  publicUrl: string;
}): Storage {
  const client = new S3Client({
    endpoint: options.endpoint,
    region: options.region,
    credentials: { accessKeyId: options.accessKeyId, secretAccessKey: options.secretAccessKey },
  });
  return prefixStorage(options.publicUrl, {
    async put(key, body, contentType) {
      await client.send(
        new PutObjectCommand({
          Bucket: options.bucket,
          Key: key,
          Body: body,
          ContentType: contentType,
          // Keys are never reused (a new upload gets a new key).
          CacheControl: "public, max-age=31536000, immutable",
        }),
      );
    },
    async delete(key) {
      await client.send(new DeleteObjectCommand({ Bucket: options.bucket, Key: key }));
    },
  });
}

/** URL prefix of the development route that serves `.data/uploads` (apps/web). */
export const LOCAL_UPLOADS_ROUTE = "/api/uploads";

/** Development substitute: files in `.data/uploads`, served by `/api/uploads/[...key]`. */
export function createLocalStorage(options: { dir?: string } = {}): Storage & {
  read(key: string): Promise<Uint8Array | null>;
} {
  const dir = options.dir ?? devUploadsDir;
  const file = (key: string) => path.join(dir, ...key.split("/"));
  const storage = prefixStorage(LOCAL_UPLOADS_ROUTE, {
    async put(key, body) {
      await mkdir(path.dirname(file(key)), { recursive: true });
      await writeFile(file(key), body);
    },
    async delete(key) {
      await rm(file(key), { force: true });
    },
  });
  return {
    ...storage,
    async read(key) {
      if (!KEY_PATTERN.test(key)) return null;
      return readFile(file(key)).catch(() => null);
    },
  };
}

/** R2/S3 when configured; local disk otherwise, except in production. */
export function createStorage(env: Record<string, string | undefined> = process.env): Storage {
  if (s3Configured(env)) {
    return createS3Storage({
      endpoint: env.S3_ENDPOINT!,
      region: env.S3_REGION || "auto",
      bucket: env.S3_BUCKET!,
      accessKeyId: env.S3_ACCESS_KEY_ID!,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY!,
      publicUrl: env.S3_PUBLIC_URL!,
    });
  }
  if (isProduction(env)) {
    throw new Error("S3_* variables are required in production.");
  }
  return createLocalStorage();
}
