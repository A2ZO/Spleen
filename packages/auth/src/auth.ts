import { drizzleAdapter } from "@better-auth/drizzle-adapter";
import { expo } from "@better-auth/expo";
import { schema, type Db } from "@spleen/db";
import { googleConfigured, isProduction } from "@spleen/infra/config";
import { createMailer, type Mailer } from "@spleen/infra/email";
import { consumeRateLimit } from "@spleen/infra/rate-limit";
import { betterAuth } from "better-auth";
import { magicLink } from "better-auth/plugins";

import { magicLinkEmail, toLocale } from "./emails";

/** Deep-link scheme of the future Expo app (`app.json` → `scheme`). */
export const APP_SCHEME = "spleen";

export const MAGIC_LINK_TTL_SECONDS = 15 * 60;

export interface AuthOptions {
  db: Db;
  /** Defaults to Brevo, or the terminal/outbox mailer in development. */
  mailer?: Mailer;
  env?: Record<string, string | undefined>;
  /** Rate limiting is always on in production; tests may turn it on explicitly. */
  rateLimit?: boolean;
}

export function createAuth({ db, mailer, env = process.env, rateLimit }: AuthOptions) {
  let defaultMailer: Mailer | undefined;
  const send = (email: Parameters<Mailer["send"]>[0]) =>
    (mailer ?? (defaultMailer ??= createMailer(env))).send(email);
  const development = !isProduction(env);

  return betterAuth({
    secret: env.BETTER_AUTH_SECRET,
    baseURL: env.BETTER_AUTH_URL,
    database: drizzleAdapter(db, {
      provider: "pg",
      schema: {
        user: schema.user,
        session: schema.session,
        account: schema.account,
        verification: schema.verification,
      },
    }),
    // Ids are UUIDs generated by Postgres (`gen_random_uuid()` defaults).
    advanced: { database: { generateId: false } },
    trustedOrigins: [
      `${APP_SCHEME}://`,
      // Expo Go / dev builds on the local network, development only.
      ...(development ? ["exp://", "exp://**", "exp://192.168.*.*:*/**"] : []),
    ],
    socialProviders: googleConfigured(env)
      ? {
          google: {
            clientId: env.GOOGLE_CLIENT_ID!,
            clientSecret: env.GOOGLE_CLIENT_SECRET!,
            prompt: "select_account",
          },
        }
      : {},
    // Signing in with Google on an address already used by a magic link joins both.
    account: { accountLinking: { enabled: true, trustedProviders: ["google"] } },
    rateLimit: {
      enabled: rateLimit ?? !development,
      window: 60,
      max: 100,
      customRules: {
        "/sign-in/magic-link": { window: 10 * 60, max: 5 },
        "/magic-link/verify": { window: 60, max: 10 },
      },
      customStorage: { consume: (key, rule) => consumeRateLimit(db, `auth:${key}`, rule) },
    },
    plugins: [
      magicLink({
        expiresIn: MAGIC_LINK_TTL_SECONDS,
        storeToken: "hashed",
        sendMagicLink: async ({ email, url, metadata }) => {
          await send(await magicLinkEmail(email, url, toLocale(metadata?.locale)));
        },
      }),
      expo(),
    ],
  });
}

export type Auth = ReturnType<typeof createAuth>;

/** What the API needs from a session: who is calling. */
export interface SessionUser {
  id: string;
  email: string;
  name: string;
}

/** Resolves the session from a cookie (web) or the Cookie header sent by the Expo app. */
export async function getSessionUser(auth: Auth, headers: Headers): Promise<SessionUser | null> {
  const session = await auth.api.getSession({ headers });
  if (!session) return null;
  const { id, email, name } = session.user;
  return { id, email, name };
}
