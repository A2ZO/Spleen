import { motion, radius, shadow } from "./scales";
import { colorRoles, themes, type Theme } from "./themes";

function themeVars(theme: Theme): string {
  return colorRoles.map((role) => `  --sp-${role}: ${theme[role]};`).join("\n");
}

/**
 * Builds the CSS consumed by Tailwind v4: runtime variables per theme
 * (dark on :root, light under [data-theme="light"]) and an `@theme inline`
 * block that exposes them as utilities (bg-surface, text-star, ...).
 */
export function buildThemeCss(): string {
  const themeBlock = [
    ...colorRoles.map((role) => `  --color-${role}: var(--sp-${role});`),
    ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`),
    ...Object.entries(shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
    `  --ease-spleen: ${motion.easing};`,
  ].join("\n");

  return `/* Generated by @spleen/design-tokens (pnpm --filter @spleen/design-tokens generate). Do not edit. */
:root,
[data-theme="dark"] {
  color-scheme: dark;
${themeVars(themes.dark)}
}

[data-theme="light"] {
  color-scheme: light;
${themeVars(themes.light)}
}

@theme inline {
${themeBlock}
}
`;
}
