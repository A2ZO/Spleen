import { motion, radius, shadow, size } from "./scales";
import { colorRoles, dark, type Theme } from "./themes";

function themeVars(theme: Theme): string {
  return colorRoles.map((role) => `  --sp-${role}: ${theme[role]};`).join("\n");
}

/**
 * Builds the CSS consumed by Tailwind v4: runtime variables on :root (single dark theme)
 * and an `@theme inline` block that exposes them as utilities (bg-surface, text-star,
 * rounded-card, shadow-button...).
 */
export function buildThemeCss(): string {
  const themeBlock = [
    ...colorRoles.map((role) => `  --color-${role}: var(--sp-${role});`),
    ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`),
    ...Object.entries(shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
    ...Object.entries(size).map(([k, v]) => `  --spacing-${k}: ${v};`),
    `  --ease-spleen: ${motion.easing};`,
    `  --ease-spring: ${motion.spring};`,
  ].join("\n");

  return `/* Generated by @spleen/design-tokens (pnpm --filter @spleen/design-tokens generate). Do not edit. */
:root {
  color-scheme: dark;
${themeVars(dark)}
}

@theme inline {
${themeBlock}
}
`;
}
